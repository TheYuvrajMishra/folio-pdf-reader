#!/usr/bin/env python3
"""Push the v2-rebuild branch to GitHub via Composio (no gh CLI on this VM).

Creates/updates refs/heads/v2-rebuild WITHOUT touching main or any tag.
First push is a ROOT commit (clean tree — the rebuild starts from scratch);
later pushes parent on the existing v2-rebuild head.

Respects .gitignore-style excludes (node_modules, android/, ios/, the
generated engine bundle, spike fixtures).

Usage:
  push-branch.py <local_dir> "<commit message>" [--account-id ca_xxx]
"""
import base64
import json
import os
import sys
import urllib.request

sys.path.insert(0, "/opt/muse/skills/custom-connector-setup/bin")
from dynamic_credentials import add_surrogate_to_request, read_json_response

EXCLUDE_DIRS = {"node_modules", ".git", "dist", "__pycache__", "android", "ios", ".expo"}
EXCLUDE_FILES = {
    "src/engine/html/engineHtml.ts",  # generated by npm run bundle:pdfjs
}
EXCLUDE_PREFIXES = ("scripts/spikes/fixtures/",)

OWNER, REPO = "TheYuvrajMishra", "folio-pdf-reader"
BRANCH = "v2-rebuild"
CRED = "custom.composio"
ALLOWED = ["backend.composio.dev"]
BASE = "https://backend.composio.dev/api/v3"


def call(slug, arguments, account_id):
    payload = {"arguments": arguments, "connected_account_id": account_id, "user_id": "default"}
    r = urllib.request.Request(
        BASE + "/tools/execute/" + slug,
        data=json.dumps(payload).encode(),
        method="POST",
        headers={"Content-Type": "application/json"},
    )
    add_surrogate_to_request(r, CRED, allowed_hosts=ALLOWED)
    try:
        with urllib.request.urlopen(r, timeout=120) as resp:
            out = read_json_response(resp)
    except Exception as e:
        try:
            body = e.read().decode()[:1000]
        except Exception:
            body = str(e)[:300]
        raise RuntimeError(f"{slug} HTTP error: {body}")
    if not out.get("successful", True):
        raise RuntimeError(f"{slug} unsuccessful: {json.dumps(out)[:800]}")
    return out["data"]


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        sys.exit(1)
    local_dir, message = sys.argv[1:3]
    account_id = None
    if "--account-id" in sys.argv:
        account_id = sys.argv[sys.argv.index("--account-id") + 1]
    if not account_id:
        raise RuntimeError("pass --account-id")

    # Re-collect including dot-directories like .github
    files = []
    for dirpath, dirnames, filenames in os.walk(local_dir):
        dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS]
        for fn in filenames:
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, local_dir).replace(os.sep, "/")
            if rel in EXCLUDE_FILES or rel.startswith(EXCLUDE_PREFIXES):
                continue
            files.append((rel, full))
    files.sort()
    if not files:
        raise RuntimeError("No files found under " + local_dir)
    print(f"{len(files)} files -> {OWNER}/{REPO}#{BRANCH} as {account_id}")

    # Existing branch head? (First push: branch doesn't exist -> root commit.)
    # The tree is always built from the full file set, so no base_tree lookup
    # is needed — the parent only links history.
    parent_sha = None
    try:
        ref = call("GITHUB_GET_A_REFERENCE",
                   {"owner": OWNER, "repo": REPO, "ref": f"heads/{BRANCH}"}, account_id)
        parent_sha = ref["object"]["sha"]
        print(f"parent: {parent_sha[:8]}")
    except RuntimeError as e:
        print(f"no existing branch ({str(e)[:60]}); creating root commit")

    entries = []
    for rel, full in files:
        with open(full, "rb") as f:
            b64 = base64.b64encode(f.read()).decode()
        blob = call("GITHUB_CREATE_A_BLOB",
                    {"owner": OWNER, "repo": REPO, "content": b64, "encoding": "base64"},
                    account_id)
        entries.append({"path": rel, "mode": "100644", "type": "blob", "sha": blob["sha"]})
    print(f"{len(entries)} blobs created")

    tree = call("GITHUB_CREATE_A_TREE",
                {"owner": OWNER, "repo": REPO, "tree": entries}, account_id)

    commit_args = {"owner": OWNER, "repo": REPO, "message": message, "tree": tree["sha"]}
    if parent_sha:
        commit_args["parents"] = [parent_sha]
    commit = call("GITHUB_CREATE_A_COMMIT", commit_args, account_id)
    new_sha = commit["sha"]
    print(f"commit: {new_sha}")

    if parent_sha:
        updated = call("GITHUB_UPDATE_A_REFERENCE",
                       {"owner": OWNER, "repo": REPO, "ref": f"heads/{BRANCH}", "sha": new_sha},
                       account_id)
    else:
        updated = call("GITHUB_CREATE_A_REFERENCE",
                       {"owner": OWNER, "repo": REPO, "ref": f"refs/heads/{BRANCH}", "sha": new_sha},
                       account_id)
    print(f"{BRANCH} ->", updated["object"]["sha"])
    print(f"DONE https://github.com/{OWNER}/{REPO}/tree/{BRANCH}")


if __name__ == "__main__":
    main()
