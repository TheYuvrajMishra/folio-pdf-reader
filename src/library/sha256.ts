/**
 * sha256.ts — compact, dependency-free SHA-256 (FIPS 180-4).
 *
 * Why not expo-crypto: the PRD names expo-crypto for duplicate detection,
 * but it is not installed and the hash input is at most ~1 MiB (first 1 MiB
 * of the PDF + 8 size bytes), so a pure implementation is fast enough
 * (~100-300 ms on device), adds zero native dependencies, and — critically —
 * is unit-testable in Node without mocking a native module.
 *
 * Platform-free: pure arithmetic over Uint8Array. No Node/RN APIs.
 */

const K = new Uint32Array([
  0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
  0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
  0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
  0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
  0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
  0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
  0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
  0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
]);

function rotr(x: number, n: number): number {
  return (x >>> n) | (x << (32 - n));
}

/** SHA-256 digest of `data` as 32 raw bytes. */
export function sha256Bytes(data: Uint8Array): Uint8Array {
  const len = data.length;
  // Padded length: smallest multiple of 64 that fits data + 0x80 + 8-byte length.
  const paddedLen = (((len + 9 + 63) >>> 6) << 6);
  const buf = new Uint8Array(paddedLen);
  buf.set(data);
  buf[len] = 0x80;
  const view = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  // 64-bit big-endian bit length. Inputs here are ≤ ~1 MiB, so no precision loss.
  view.setUint32(paddedLen - 8, Math.floor((len * 8) / 0x100000000));
  view.setUint32(paddedLen - 4, (len * 8) >>> 0);

  let h0 = 0x6a09e667;
  let h1 = 0xbb67ae85;
  let h2 = 0x3c6ef372;
  let h3 = 0xa54ff53a;
  let h4 = 0x510e527f;
  let h5 = 0x9b05688c;
  let h6 = 0x1f83d9ab;
  let h7 = 0x5be0cd19;

  const w = new Uint32Array(64);
  for (let off = 0; off < paddedLen; off += 64) {
    for (let i = 0; i < 16; i++) {
      w[i] = view.getUint32(off + i * 4);
    }
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) | 0;
    }
    let a = h0;
    let b = h1;
    let c = h2;
    let d = h3;
    let e = h4;
    let f = h5;
    let g = h6;
    let h = h7;
    for (let i = 0; i < 64; i++) {
      const s1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (h + s1 + ch + K[i] + w[i]) | 0;
      const s0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (s0 + maj) | 0;
      h = g;
      g = f;
      f = e;
      e = (d + t1) | 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) | 0;
    }
    h0 = (h0 + a) | 0;
    h1 = (h1 + b) | 0;
    h2 = (h2 + c) | 0;
    h3 = (h3 + d) | 0;
    h4 = (h4 + e) | 0;
    h5 = (h5 + f) | 0;
    h6 = (h6 + g) | 0;
    h7 = (h7 + h) | 0;
  }

  const out = new Uint8Array(32);
  const outView = new DataView(out.buffer);
  const hs = [h0, h1, h2, h3, h4, h5, h6, h7];
  for (let i = 0; i < 8; i++) {
    outView.setUint32(i * 4, hs[i] >>> 0);
  }
  return out;
}

const HEX = '0123456789abcdef';

/** SHA-256 digest of `data` as a lowercase hex string. */
export function sha256Hex(data: Uint8Array): string {
  const digest = sha256Bytes(data);
  let s = '';
  for (let i = 0; i < digest.length; i++) {
    s += HEX[digest[i] >>> 4] + HEX[digest[i] & 0x0f];
  }
  return s;
}

/** SHA-256 of a UTF-8 string as lowercase hex (convenience for tests/tools). */
export function sha256HexOfString(text: string): string {
  return sha256Hex(new TextEncoder().encode(text));
}
